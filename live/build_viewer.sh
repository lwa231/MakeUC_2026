#!/usr/bin/env bash
# Build the Brace Tracker viewer (main.cpp) on macOS without modifying main.cpp.
# Idempotent. Output: <repo>/build/viewer
set -euo pipefail

fail() { echo "build_viewer.sh: ERROR: $*" >&2; exit 1; }

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO="$(cd "$HERE/.." && pwd)"
TP="$HERE/third_party"
GLAD_DIR="$TP/glad"
SHIM_DIR="$TP/shim"
BUILD="$REPO/build"
OUT="$BUILD/viewer"

[ "$(uname -s)" = "Darwin" ] || fail "this script targets macOS"
[ -f "$REPO/main.cpp" ] || fail "main.cpp not found in $REPO"
command -v brew >/dev/null 2>&1 || fail "Homebrew not found (https://brew.sh)"
command -v clang++ >/dev/null 2>&1 || fail "clang++ not found (run: xcode-select --install)"
command -v python3 >/dev/null 2>&1 || fail "python3 not found"

# 1. Homebrew deps ------------------------------------------------------------
for pkg in glfw glm; do
  if ! brew list --versions "$pkg" >/dev/null 2>&1; then
    echo "==> brew install $pkg"
    brew install "$pkg" || fail "brew install $pkg failed"
  fi
done
BP="$(brew --prefix)"
GLFW_PREFIX="$(brew --prefix glfw)"
GLM_PREFIX="$(brew --prefix glm)"
[ -f "$GLFW_PREFIX/include/GLFW/glfw3.h" ] || fail "glfw3.h not found under $GLFW_PREFIX"
[ -f "$GLM_PREFIX/include/glm/glm.hpp" ] || fail "glm.hpp not found under $GLM_PREFIX"

mkdir -p "$BUILD"

# 2. glad v1 (GL 3.3 core), generated in a throwaway venv -----------------------
if [ ! -f "$GLAD_DIR/include/glad/glad.h" ] || [ ! -f "$GLAD_DIR/include/KHR/khrplatform.h" ] \
   || [ ! -f "$GLAD_DIR/src/glad.c" ]; then
  echo "==> generating glad (GL 3.3 core)"
  VENV="$BUILD/glad-venv"
  [ -x "$VENV/bin/python" ] || python3 -m venv "$VENV" || fail "could not create venv"
  "$VENV/bin/python" -m pip install --quiet --disable-pip-version-check "glad==0.1.36" certifi \
    || fail "pip install glad==0.1.36 failed"
  rm -rf "$GLAD_DIR"; mkdir -p "$GLAD_DIR"
  SSL_CERT_FILE="$("$VENV/bin/python" -c 'import certifi;print(certifi.where())')" \
  "$VENV/bin/python" -m glad --generator c --api gl=3.3 --profile core --out-path "$GLAD_DIR" \
    || fail "glad generation failed"
  [ -f "$GLAD_DIR/src/glad.c" ] || fail "glad output missing"
fi

# 3. include shim: <GLFW/include/GLFW/glfw3.h> -> homebrew glfw3.h -------------
mkdir -p "$SHIM_DIR/GLFW/include/GLFW"
SHIM_H="$SHIM_DIR/GLFW/include/GLFW/glfw3.h"
printf '// auto-generated by build_viewer.sh\n#include "%s/include/GLFW/glfw3.h"\n' "$GLFW_PREFIX" > "$SHIM_H"

# 4. compile --------------------------------------------------------------------
echo "==> compiling"
CXXFLAGS=(-std=c++17 -O2 -Wall -Wno-deprecated-declarations
  -I"$GLAD_DIR/include" -I"$SHIM_DIR" -I"$GLM_PREFIX/include" -I"$GLFW_PREFIX/include")
clang -O2 -c -I"$GLAD_DIR/include" "$GLAD_DIR/src/glad.c" -o "$BUILD/glad.o" \
  || fail "compiling glad.c failed"
clang++ "${CXXFLAGS[@]}" "$REPO/main.cpp" "$BUILD/glad.o" -o "$OUT" \
  -L"$GLFW_PREFIX/lib" -lglfw \
  -framework Cocoa -framework IOKit -framework OpenGL -framework CoreVideo \
  || fail "compiling/linking main.cpp failed"

[ -x "$OUT" ] || fail "build produced no binary"
echo "==> built: $OUT"
echo "$OUT"
